#!/usr/bin/env bash
# install_gear_second.sh — Install gear-second as an editable pip package + PATH symlinks
# Run from ~/projects/gear-second/ or anywhere with: bash ~/projects/gear-second/scripts/install_gear_second.sh
set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
INSTALL_DIR="$HOME/.local/bin"

echo "Gear Second — Install Script"
echo "Project: $PROJECT_DIR"
echo ""

# Create ~/.local/bin if needed
mkdir -p "$INSTALL_DIR"

# Attempt pip install -e . (editable install)
if python3 -m pip install -e "$PROJECT_DIR" --quiet --break-system-packages 2>/dev/null; then
    echo "  ✓ pip editable install succeeded"
    INSTALLED_VIA_PIP=true
else
    INSTALLED_VIA_PIP=false
    echo "  ⚠  pip editable install failed or unavailable — using PATH wrapper instead"
fi

# Always write/overwrite the PATH wrapper scripts
# This ensures gear-second works even if pip install didn't register the entry point
cat > "$INSTALL_DIR/gear-second" << EOF
#!/usr/bin/env bash
# Gear Second launcher — P51 Brain governed failover mode
# Auto-generated by install_gear_second.sh
export PYTHONPATH="${PROJECT_DIR}:\${PYTHONPATH}"
exec python3 -m gear_second.cli "\$@"
EOF

cat > "$INSTALL_DIR/gearsecond" << EOF
#!/usr/bin/env bash
export PYTHONPATH="${PROJECT_DIR}:\${PYTHONPATH}"
exec python3 -m gear_second.cli "\$@"
EOF

chmod +x "$INSTALL_DIR/gear-second" "$INSTALL_DIR/gearsecond"

echo "  ✓ Launcher installed: $INSTALL_DIR/gear-second"
echo "  ✓ Alias installed:    $INSTALL_DIR/gearsecond"

# PATH check
if [[ ":$PATH:" != *":$INSTALL_DIR:"* ]]; then
    echo ""
    echo "  NOTE: $INSTALL_DIR is not in your PATH."
    echo "  Add this to ~/.bashrc or ~/.zshrc:"
    echo "    export PATH=\"\$HOME/.local/bin:\$PATH\""
fi

echo ""
echo "  Verify: gear-second status"
echo "  Brief:  gear-second brief"
echo "  Start:  gear-second start --mode auto"
echo ""
echo "Done."
